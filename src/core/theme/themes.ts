export const ALL_THEMES: ThemePalette[] = [...LIGHT_THEMES, ...DARK_THEMES];

export function findThemeById(id: string, fallbackMode: "light" | "dark"): ThemePalette {
  const found = ALL_THEMES.find((t) => t.id === id);
  if (found) return found;
  return fallbackMode === "dark" ? DARK_THEMES[0] : LIGHT_THEMES[0];
}

